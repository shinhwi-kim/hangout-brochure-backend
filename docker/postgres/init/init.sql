    ON ingestion_raw_seoul_cultural_hangouts (content_hash);

-- Each source publishes its own taxonomy, so transforming a source means translating its
-- labels into our categories. Kept as data rather than code so the mapping can change
-- without a deploy. A source label may map to more than one category.
CREATE TABLE IF NOT EXISTS ingestion_category_mappings (
    source_name VARCHAR(100) NOT NULL REFERENCES ingestion_sources (source_name),
    source_category TEXT NOT NULL,
    category_id INT NOT NULL REFERENCES hangout_categories (id),
    PRIMARY KEY (source_name, source_category, category_id)
);

